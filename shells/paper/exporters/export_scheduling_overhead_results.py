"""Export the scheduling-control idle fractions as LaTeX macros for the paper.

The inputs are analyzed Nsight JSON files written by ``loopsgl.benchmark.analyze_nsys``.
Each input must contain a warning-free ``benchmark.generate`` measurement.
The analyzer requires exactly one generation range.
These fractions cover the full generation call, including batch filling and draining.

Example:
    uv run python shells/paper/exporters/export_scheduling_overhead_results.py \
        --sync outputs/ablations/scheduling-overhead/sync_analysis.json \
        --async-immediate outputs/ablations/scheduling-overhead/async_analysis.json \
        --lookahead outputs/ablations/scheduling-overhead/lookahead_analysis.json \
        --output docs/paper/figs/cdb_async_overhead_data.tex
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

VARIANTS = (
    ("sync", "idleSync"),
    ("async_immediate", "idleAsyncImmediate"),
    ("lookahead", "idleLookahead"),
)


def load_idle_percent(path: Path) -> float:
    """Load and validate one measured full-generation GPU idle fraction."""
    payload: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("measured_label") != "benchmark.generate":
        raise ValueError(f"{path} was not measured over benchmark.generate")
    warnings = payload.get("diagnostics", {}).get("warnings")
    if warnings != []:
        raise ValueError(f"{path} has capture diagnostics warnings: {warnings!r}")
    try:
        fraction = float(payload["measured"]["gpu_idle_fraction"])
    except (KeyError, TypeError, ValueError) as error:
        raise ValueError(f"{path} has no valid GPU idle fraction") from error
    if not 0.0 <= fraction <= 1.0:
        raise ValueError(f"{path} has invalid GPU idle fraction {fraction}")
    return 100.0 * fraction


def render_macros(values: dict[str, float]) -> str:
    """Render plot values and two-decimal labels from the validated percentages."""
    lines = [
        "% Generated by shells/paper/exporters/export_scheduling_overhead_results.py.",
        "% Measurement window: benchmark.generate.",
    ]
    for key, macro in VARIANTS:
        value = values[key]
        lines.append(f"\\def\\{macro}{{{value:.3f}}}")
        lines.append(f"\\def\\{macro}Label{{{value:.2f}\\%}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--sync", type=Path, required=True)
    parser.add_argument("--async-immediate", type=Path, required=True)
    parser.add_argument("--lookahead", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        values = {
            "sync": load_idle_percent(args.sync),
            "async_immediate": load_idle_percent(args.async_immediate),
            "lookahead": load_idle_percent(args.lookahead),
        }
    except (OSError, ValueError, TypeError) as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_macros(values), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
